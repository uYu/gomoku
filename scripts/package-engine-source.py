"""Publish exact corresponding engine sources, build recipe, configs and weights."""
from pathlib import Path
import tarfile
root = Path(__file__).resolve().parents[1]
paths = [root / 'third_party/rapfi', root / 'models/rapfi', root / 'CMakeLists.txt', root / 'cpp', root / 'scripts/build-rules.sh', root / 'data/raw', root / 'scripts/train-policy.py', root / 'scripts/prepare-training.py', root / 'THIRD_PARTY_NOTICES.md', root / 'docs/ENGINE.md', root / 'docs/DATA_SOURCES.md', root / 'docs/NNUE_FROM_SCRATCH.md', root / 'docs/FREESTYLE_TRIAL.md', root / 'models/training-report.json', root / 'models/training-stats.csv', root / 'data/README.md', root / 'LICENSE', root / 'scripts/build-wasm.sh', root / 'scripts/build-native.sh', root / 'scripts/stage-engine.py', root / 'scripts/package-engine-source.py']
with tarfile.open(root / 'public/engine/source.tar.gz', 'w:gz') as archive:
    def select(info):
        # Networks is generated by stage-engine.py from the included models.
        return None if '/Networks' in info.name or '/.git/' in info.name else info
    for path in paths:
        archive.add(path, arcname='gomoku-engine/' + str(path.relative_to(root)), filter=select)
