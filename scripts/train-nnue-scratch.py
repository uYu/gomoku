#!/usr/bin/env python3
"""Random-init full-width Mix9svq trial. No pretrained weights or distillation.

Uses the pinned official PyTorch model and quantized serializer unchanged.
All weights and derived data stay local to .build for offline research.
"""
import argparse
import hashlib
import json
import math
import os
import random
import sys
import time
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
os.environ.setdefault('KEOPS_CACHE_FOLDER',str(ROOT/'.build/keops'))
sys.path.insert(0,str(ROOT/'third_party/nnue-trainer'))
import numpy as np
import torch
import torch.nn.functional as F
from accelerate import PartialState
from model import build_model
from utils.training_utils import weights_init
from nnue_cpu import install
install()
MODEL_ARGS={'dim_middle':128,'dim_feature':64,'dim_policy':32,'dim_value':64,'dim_dwconv':32,'input_type':'basicns','codebook_size':65536,'num_codebooks':1,'kmeans_init':False,'ema_decay':0.995,'threshold_ema_dead_code':0.005}
SEED=20261029

def sha(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as stream:
        for b in iter(lambda:stream.read(1024*1024),b''):h.update(b)
    return h.hexdigest()

def load_samples(path):
    with np.load(path,allow_pickle=False) as a:
        return {key:torch.from_numpy(np.ascontiguousarray(a[key])) for key in ['board','line','legal','policy','value']}

def batch(data,indices,color):
    # The bit mask is generated by the same Rapfi forbidden-rule implementation.
    packed=data['legal'][indices].numpy()
    legal=torch.from_numpy(np.unpackbits(packed,axis=1,count=225,bitorder='little').astype(bool))
    boards=data['board'][indices].float()
    stm=(boards.sum((1,2,3)).remainder(2)*2-1).reshape(-1,1) if color=='mixed' else torch.full((len(indices),1),-1. if color=='black' else 1.)
    return {'board_input':boards,'line_encoding':data['line'][indices], 'stm_input':stm},legal,data['policy'][indices],data['value'][indices]

def losses(model,data,indices,color):
    inputs,legal,policy,value=batch(data,indices,color)
    result=model(inputs)
    logits=result[1].flatten(1).masked_fill(~legal,-10000.)
    value_loss=F.cross_entropy(result[0],value)
    policy_loss=F.cross_entropy(logits,policy)
    auxiliary=sum(result[2].values()) if result[2] else torch.zeros(())
    return value_loss,policy_loss,auxiliary,logits,policy

@torch.no_grad()
def evaluate(model,data,color,batch_size,limit=None):
    model.eval();n=len(data['policy'])
    indices=np.arange(n)
    if limit and n>limit:indices=np.random.default_rng(SEED).choice(n,limit,replace=False)
    v=p=correct=count=0
    for at in range(0,len(indices),batch_size):
        chosen=torch.tensor(indices[at:at+batch_size],dtype=torch.long)
        value,policy,_,logits,target=losses(model,data,chosen,color)
        v+=float(value)*len(chosen);p+=float(policy)*len(chosen)
        correct+=int((logits.argmax(1)==target).sum());count+=len(chosen)
    model.train()
    return {'positions':count,'value_ce':v/count,'policy_ce':p/count,'joint_ce':(v+p)/count,'policy_accuracy':correct/count}

def save_checkpoint(path,model,step,color,optimizer=None):
    value={'model':model.state_dict(),'iteration':str(step),'initialization':'random; no pretrained checkpoint','color':color}
    if optimizer is not None:value['optimizer']=optimizer.state_dict()
    temporary=path.with_suffix('.tmp');torch.save(value,temporary);temporary.replace(path)

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--color',choices=['black','white','mixed'],required=True)
    parser.add_argument('--rule',choices=['renju','freestyle'],default='renju')
    parser.add_argument('--run',default='.build/experiments/mix9svq-scratch-r15-v2')
    parser.add_argument('--samples',default='.build/training/nnue-samples-v2')
    parser.add_argument('--steps',type=int,default=2000)
    parser.add_argument('--batch-size',type=int,default=16)
    parser.add_argument('--threads',type=int,default=2)
    parser.add_argument('--validate-every',type=int,default=250)
    options=parser.parse_args()
    if options.steps<1 or options.batch_size<1:parser.error('Positive steps and batch size required')
    run=(ROOT/options.run/options.color).resolve();samples=(ROOT/options.samples).resolve()
    if not run.is_relative_to(ROOT/'.build'):parser.error('Experimental models must stay in .build')
    run.mkdir(parents=True,exist_ok=True)
    if (run/'initial.pt').exists():parser.error('Existing run; use a fresh directory to preserve results')
    PartialState(cpu=True);torch.set_num_threads(options.threads)
    seed=SEED+(options.color=='white');torch.manual_seed(seed);np.random.seed(seed);random.seed(seed)
    manifest=json.loads((samples/'manifest.json').read_text())
    if manifest['rule']!=options.rule:raise ValueError('Sample/export rule mismatch')
    datasets={}
    for split in ['train','validation','test']:
        path=samples/f'{split}-{options.color}.npz'
        if sha(path)!=manifest['samples'][f'{split}-{options.color}']['sha256']:raise ValueError('Sample checksum mismatch')
        datasets[split]=load_samples(path)
    model=build_model('mix9svq',**MODEL_ARGS)
    model.apply(weights_init({}))  # Initializes all custom directional layers too.
    assert all(torch.isfinite(p).all() for p in model.parameters())
    optimizer=torch.optim.AdamW((p for p in model.parameters() if p.requires_grad),lr=.001,weight_decay=1e-7)
    clipping=[(dict(model.named_parameters())[name],rule['min_weight'],rule['max_weight']) for rule in model.weight_clipping for name in rule['params']]
    save_checkpoint(run/'initial.pt',model,0,options.color)
    config={'model_type':'mix9svq','model_args':MODEL_ARGS,'rule':options.rule,'seed':seed,'initialization':'random','pretrained_checkpoint':None,'distillation':False,'steps':options.steps,'batch_size':options.batch_size,'threads':options.threads,'sample_manifest_sha256':sha(samples/'manifest.json'),'initial_checkpoint_sha256':sha(run/'initial.pt'),'parameters':sum(p.numel() for p in model.parameters()),'gradient_parameters':sum(p.numel() for p in model.parameters() if p.requires_grad),'codebook_training':'EMA updated from random initialization; mapping/conv/heads trained by backpropagation','loss':'Legal-move masked policy cross entropy + WDL cross entropy + VQ auxiliary loss','checkpoint_selection':'minimum validation joint CE; test not used for selection','learning_rate':'50 step warmup to .001; cosine to .0002','torch':torch.__version__,'training_script_sha256':sha(Path(__file__)),'cpu_backend_sha256':sha(ROOT/'scripts/nnue_cpu.py')}
    (run/'config.json').write_text(json.dumps(config,indent=2)+'\n')
    first=evaluate(model,datasets['validation'],options.color,options.batch_size,512)
    best,best_step=first['joint_ce'],0
    save_checkpoint(run/'best.pt',model,0,options.color)
    start=time.monotonic();curve=[{'step':0,'validation':first}]
    generator=np.random.default_rng(seed)
    history=[]
    def status(step,extra=None):
        entry={'status':'training','color':options.color,'step':step,'steps':options.steps,'rows':step*options.batch_size,'elapsed_seconds':time.monotonic()-start,'best_step':best_step,**(extra or {})}
        (run/'status.json').write_text(json.dumps(entry,indent=2)+'\n')
    status(0,{'initial_validation':first})
    print(json.dumps({'color':options.color,'parameters':config['parameters'],'initial_validation':first}),flush=True)
    model.train()
    for step in range(1,options.steps+1):
        lr=.001*min(1.,step/50.) if step<=50 else .0002+.0008*(1+math.cos(math.pi*(step-50)/max(1,options.steps-50)))/2
        for group in optimizer.param_groups:group['lr']=lr
        indices=torch.tensor(generator.integers(0,len(datasets['train']['policy']),options.batch_size),dtype=torch.long)
        optimizer.zero_grad(set_to_none=True)
        v,p,aux,_,_=losses(model,datasets['train'],indices,options.color)
        total=v+p+aux
        if not torch.isfinite(total):raise RuntimeError(f'Nonfinite loss at step {step}')
        total.backward();torch.nn.utils.clip_grad_norm_(model.parameters(),1.)
        optimizer.step()
        with torch.no_grad():
            for parameter,low,high in clipping:parameter.clamp_(low,high)
        history.append([float(v.detach()),float(p.detach()),float(aux.detach())])
        if step%25==0:
            average=np.mean(history[-25:],axis=0).tolist()
            status(step,{'recent_value_policy_vq_loss':average})
            print(json.dumps({'color':options.color,'step':step,'elapsed':round(time.monotonic()-start,1),'losses':average}),flush=True)
        if step%options.validate_every==0 or step==options.steps:
            val=evaluate(model,datasets['validation'],options.color,options.batch_size,512)
            if val['joint_ce']<best:
                best,best_step=val['joint_ce'],step
                save_checkpoint(run/'best.pt',model,step,options.color)
            save_checkpoint(run/'last.pt',model,step,options.color,optimizer)
            curve.append({'step':step,'validation':val,'train_recent':np.mean(history[-100:],axis=0).tolist(),'elapsed_seconds':time.monotonic()-start})
            (run/'curve.json').write_text(json.dumps(curve,indent=2)+'\n')
            print(json.dumps({'color':options.color,'step':step,'validation':val,'selected':best_step}),flush=True)
    model.load_state_dict(torch.load(run/'best.pt',weights_only=True)['model'])
    final_val=evaluate(model,datasets['validation'],options.color,options.batch_size)
    final_test=evaluate(model,datasets['test'],options.color,options.batch_size)
    selected_state={key:value.clone() for key,value in model.state_dict().items()}
    model.load_state_dict(torch.load(run/'initial.pt',weights_only=True)['model'])
    initial_test=evaluate(model,datasets['test'],options.color,options.batch_size)
    model.load_state_dict(selected_state);model.eval()
    report={**config,'color':options.color,'selected_step':best_step,'validation_initial_subset':first,'validation_final':final_val,'test_initial':initial_test,'test_final':final_test,'elapsed_seconds':time.monotonic()-start,'selected_checkpoint_sha256':sha(run/'best.pt'),'claim':'A short CPU trial from random initialization, not convergence or evidence of beating Rapfi.'}
    (run/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    (run/'status.json').write_text(json.dumps({'status':'exporting','step':options.steps,'selected_step':best_step},indent=2)+'\n')
    # Import after training to keep serializer-only dependencies off the hot path.
    from export import export_serialization
    network=run/'network.bin.lz4'
    with torch.no_grad():
        export_serialization(str(network),'lz4','mix9svq',model,{'rules':[options.rule],'boardsizes':[15]},True)
    report['network_sha256']=sha(network)
    (run/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    (run/'status.json').write_text(json.dumps({'status':'exported','step':options.steps,'selected_step':best_step,'network_sha256':report['network_sha256']},indent=2)+'\n')
    print(json.dumps(report,indent=2),flush=True)
if __name__=='__main__':
    try:main()
    except BaseException as error:
        # Full traceback remains in the log; failed runs never report exported.
        print('NNUE_RUN_FAILED',repr(error),flush=True)
        raise
